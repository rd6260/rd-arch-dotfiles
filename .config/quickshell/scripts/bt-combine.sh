#!/usr/bin/env bash
# Combined audio output: one virtual sink ("combine_bt") that plays to several
# output devices at once.
#
# usage: bt-combine.sh on | off | toggle | status
#        bt-combine.sh members                 print selected sink names (one per line)
#        bt-combine.sh set-members NAME...     save selection (restarts the sink if on)
#
# The selection is kept in $STATE. With no selection saved, every Bluetooth
# output is included. The sink lives in its own PipeWire instance (config
# generated into $XDG_RUNTIME_DIR), run as a systemd user unit, so it can be
# toggled without restarting the main PipeWire daemon.
set -euo pipefail

UNIT=quickshell-bt-combine.service
STATE="${XDG_STATE_HOME:-$HOME/.local/state}/quickshell/combine-sinks"
CONF="${XDG_RUNTIME_DIR:-/run/user/$(id -u)}/quickshell-combine.conf"
UNIT_FILE="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user/$UNIT"

is_on() { systemctl --user is-active --quiet "$UNIT"; }

members() { [[ -s $STATE ]] && grep -v '^\s*$' "$STATE" || true; }

# One stream.rules match per member. Bluetooth node names end in a profile
# counter (bluez_output.<MAC>.1) that can change, so match those by MAC.
match_lines() {
    local name any=0
    while IFS= read -r name; do
        any=1
        if [[ $name =~ ^bluez_output\.([0-9A-F_]+)\. ]]; then
            printf '                    { media.class = "Audio/Sink" node.name = "~bluez_output\\\\.%s\\\\..*" }\n' "${BASH_REMATCH[1]}"
        else
            printf '                    { media.class = "Audio/Sink" node.name = "%s" }\n' "$name"
        fi
    done < <(members)
    if (( ! any )); then
        echo '                    { media.class = "Audio/Sink" node.name = "~bluez_output\\..*" }'
    fi
}

write_conf() {
    cat > "$CONF" <<CONF
# Generated by bt-combine.sh, do not edit.
context.properties = { log.level = 0 }
context.spa-libs = {
    audio.convert.* = audioconvert/libspa-audioconvert
    support.*       = support/libspa-support
}
context.modules = [
    { name = libpipewire-module-rt args = { } flags = [ ifexists nofail ] }
    { name = libpipewire-module-protocol-native }
    { name = libpipewire-module-client-node }
    { name = libpipewire-module-adapter }
    { name = libpipewire-module-combine-stream
      args = {
          combine.mode = sink
          node.name = "combine_bt"
          node.description = "Combined Output"
          combine.latency-compensate = false
          combine.props = { audio.position = [ FL FR ] }
          stream.rules = [
              {   matches = [
$(match_lines)
                  ]
                  actions = { create-stream = { } }
              }
          ]
      }
    }
]
CONF
}

ensure_unit() {
    local want="[Unit]
Description=Quickshell combined audio output
After=pipewire.service
BindsTo=pipewire.service

[Service]
ExecStart=/usr/bin/pipewire -c $CONF
Restart=on-failure
"
    if [[ ! -f $UNIT_FILE || "$(cat "$UNIT_FILE")" != "$want" ]]; then
        mkdir -p "$(dirname "$UNIT_FILE")"
        printf '%s' "$want" > "$UNIT_FILE"
        systemctl --user daemon-reload
    fi
}

case "${1:-status}" in
    on)      ensure_unit; write_conf; systemctl --user start "$UNIT" ;;
    off)     systemctl --user stop "$UNIT" 2>/dev/null || true ;;
    toggle)  if is_on; then "$0" off; else "$0" on; fi ;;
    status)  if is_on; then echo on; else echo off; fi ;;
    members) members ;;
    set-members)
        shift
        mkdir -p "$(dirname "$STATE")"
        printf '%s\n' "$@" > "$STATE"
        if is_on; then write_conf; systemctl --user restart "$UNIT"; fi ;;
    *) echo "usage: $0 on|off|toggle|status|members|set-members NAME..." >&2; exit 2 ;;
esac
